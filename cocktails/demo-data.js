/* Drink of the Week schedule is anchored to the current week,
   so the demo always has a "This Week" feature. Offsets are in weeks. */
function demoWeek(offset) {
  const d = new Date(); d.setHours(0,0,0,0);
  const day = (d.getDay() + 6) % 7;           // Monday = 0
  d.setDate(d.getDate() - day + offset * 7);
  return d.toISOString().slice(0,10);
}

